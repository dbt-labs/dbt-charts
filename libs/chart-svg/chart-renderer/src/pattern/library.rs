//! The motif library: tiles and ramps generated once by `chart_svg_dev/gen_pattern_motifs.py`
//! and read from `data/pattern_motifs.json`. The data carries geometry only; ink and ground
//! are painted per series.

use scene::{Attrs, Node, PathCommand, PathData, Role, Shape, Transform};
use serde::{Deserialize, Deserializer};
use std::collections::BTreeMap;
use std::sync::LazyLock;

/// A mark of a tile, in tile coordinates.
#[derive(Debug, Deserialize)]
#[serde(untagged)]
pub enum Mark {
    Circles { circles: Vec<[f64; 2]>, r: f64 },
    Filled {
        #[serde(deserialize_with = "path_data")]
        path: PathData,
        fill: bool,
        fill_rule: String,
    },
    Stroked {
        #[serde(deserialize_with = "path_data")]
        path: PathData,
        stroke_width: f64,
        linecap: String,
    },
}

/// A tile path as the generator writes it: `M`, `L`, `Q`, relative `h` and `v`, and `Z`, with
/// space-separated numbers. A quadratic is the cubic that draws the same curve.
fn path_data<'de, D: Deserializer<'de>>(de: D) -> Result<PathData, D::Error> {
    parse_tile_path(&String::deserialize(de)?).map_err(serde::de::Error::custom)
}

fn parse_tile_path(text: &str) -> Result<PathData, String> {
    let mut path = PathData::new();
    let mut at = (0.0, 0.0);
    let mut start = at;
    let mut rest = text;
    while let Some(command) = rest.chars().next() {
        let end = rest[1..].find(|c: char| c.is_ascii_alphabetic()).map_or(rest.len(), |next| next + 1);
        let numbers: Vec<f64> = rest[1..end].split_whitespace().map(str::parse).collect::<Result<_, _>>().map_err(|e| format!("tile path `{text}`: {e}"))?;
        rest = &rest[end..];
        path = match (command, numbers.as_slice()) {
            ('M', &[x, y]) => {
                start = (x, y);
                path.move_to(x, y)
            }
            ('L', &[x, y]) => path.line_to(x, y),
            ('h', &[dx]) => path.line_to(at.0 + dx, at.1),
            ('v', &[dy]) => path.line_to(at.0, at.1 + dy),
            ('Q', &[qx, qy, x, y]) => {
                let toward = |p: (f64, f64)| (p.0 + 2.0 / 3.0 * (qx - p.0), p.1 + 2.0 / 3.0 * (qy - p.1));
                let (c1, c2) = (toward(at), toward((x, y)));
                PathData(path.0.into_iter().chain([PathCommand::C(c1.0, c1.1, c2.0, c2.1, x, y)]).collect())
            }
            ('Z', []) => path.close(),
            _ => return Err(format!("tile path `{text}`: `{command}` with {} numbers", numbers.len())),
        };
        at = match path.commands().last() {
            Some(PathCommand::Z) => start,
            Some(&(PathCommand::M(x, y) | PathCommand::L(x, y) | PathCommand::C(_, _, _, _, x, y))) => (x, y),
            _ => at,
        };
    }
    Ok(path)
}

/// One repeating tile.
#[derive(Debug, Deserialize)]
pub struct Tile {
    pub width: f64,
    pub height: f64,
    /// The distance between repeats of the motif's pattern, in px.
    pub spacing: f64,
    /// The share of the tile the marks cover.
    pub coverage: f64,
    /// Where in the tile (px) a legend key's window starts: the crop of the tile the key shows.
    pub key_window: [f64; 2],
    /// A pixel-grid tile: its legend key draws at full scale, since shrinking would blur its grain.
    #[serde(default)]
    pub crisp: bool,
    pub marks: Vec<Mark>,
}

/// One step of a ramp: a tile plus how the step is painted.
#[derive(Debug, Deserialize)]
pub struct Step {
    #[serde(flatten)]
    pub tile: Tile,
    /// Marks sit on an ink ground in the ground color.
    pub inverse: bool,
    /// CIE L* of the step rendered in black on white: the lightness its flat tint reproduces.
    #[serde(rename = "L_star")]
    pub l_star: f64,
}

#[derive(Debug, Deserialize)]
pub struct Library {
    /// Rendered ink over nominal coverage: a flat tint is mixed at `coverage * flat_k`.
    pub flat_k: f64,
    pub motifs: BTreeMap<String, Tile>,
    /// `ramps[name][step count]`: the tiles of a ramp of that many steps, lightest first.
    pub ramps: BTreeMap<String, BTreeMap<String, Vec<Step>>>,
}

static SHIPPED: LazyLock<Library> = LazyLock::new(|| {
    serde_json::from_str(include_str!("../../data/pattern_motifs.json"))
        .expect("data/pattern_motifs.json is generated by gen_pattern_motifs.py and always parses")
});

/// The library the engine ships.
pub fn shipped() -> &'static Library {
    &SHIPPED
}

/// A legend key's size. Legend keys are an exception to the 1.5 px stroke floor and the
/// 4 px period rule: the key draws its tile at [`KEY_SCALE`], so a 4 px period is 3 px there
/// (a `crisp` tile draws at full scale).
pub const KEY_W: f64 = 16.0;
pub const KEY_H: f64 = 12.0;
pub const KEY_SCALE: f64 = 0.75;
/// The prefix of a legend key's paint id: the legend sizes a fill with this prefix as a key.
pub const KEY_PREFIX: &str = "dbt-key-";

/// The `<defs>` of a legend key `key_id`: a `KEY_W` x `KEY_H` pattern holding the key's fill
/// and a 1 px outline in `ink`. The key's fill is the `tile_id` pattern drawn at [`KEY_SCALE`]
/// with its `key_window` at the key's top-left: a rect filled with the tile, inside a group
/// that scales and shifts the tile's user space.
pub fn key_node(key_id: &str, tile_id: &str, tile: &Tile, ink: &str) -> Node {
    let key_scale = if tile.crisp { 1.0 } else { KEY_SCALE };
    let [wx, wy] = tile.key_window;
    let fill = Attrs::new().set("fill", format!("url(#{tile_id})"));
    let window = Node::rect(Role::Chrome, (wx, wy, KEY_W / key_scale, KEY_H / key_scale), fill);
    let cropped = Node::group(Role::Chrome, Attrs::new(), vec![window])
        .translate(-wx * key_scale, -wy * key_scale)
        .with_transform(Transform::Scale(key_scale));
    let outline = Node::rect(
        Role::Chrome,
        (0.5, 0.5, KEY_W - 1.0, KEY_H - 1.0),
        Attrs::new().set("fill", "none").set("stroke", ink).num("stroke-width", 1.0),
    );
    let attrs = Attrs::new().set("id", key_id).set("patternUnits", "userSpaceOnUse");
    Node::new(Role::Chrome, attrs, Shape::Pattern { w: KEY_W, h: KEY_H, transform: None, children: vec![cropped, outline] })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Where the key's window rect lands in the key's own space, as its two corners.
    fn window_in_key(key: &Node) -> [(f64, f64); 2] {
        let cropped = &key.children()[0];
        let window = &cropped.children()[0];
        let Shape::Rect { x, y, w, h, .. } = window.shape else { panic!("the window is a rect") };
        [(x, y), (x + w, y + h)].map(|corner| cropped.affine().apply(corner))
    }

    #[test]
    fn a_tiled_key_draws_the_tile_at_three_quarters_from_its_window_under_an_ink_outline() {
        let tile = Tile { width: 8.0, height: 8.0, spacing: 5.6, coverage: 0.3, key_window: [4.0, 0.0], crisp: false, marks: Vec::new() };
        let key = key_node("k", "t", &tile, "#123456");
        assert_eq!(window_in_key(&key), [(0.0, 0.0), (KEY_W, KEY_H)]);
        let cropped = &key.children()[0];
        assert_eq!(cropped.affine().apply((0.0, 0.0)), (-3.0, 0.0), "the tile's origin sits at minus the window, scaled");
        assert_eq!(cropped.children()[0].attrs.get("fill"), Some("url(#t)"));
        assert_eq!(key.children()[1].attrs.get("stroke"), Some("#123456"));
    }

    fn parsed(text: &str) -> Vec<PathCommand> {
        parse_tile_path(text).unwrap().0
    }

    #[test]
    fn a_quadratic_is_the_cubic_that_draws_the_same_curve() {
        let cubic = PathCommand::C(2.0, 0.0, 3.0, 1.0, 3.0, 3.0);
        assert_eq!(parsed("M0 0Q3 0 3 3"), [PathCommand::M(0.0, 0.0), cubic]);
    }

    #[test]
    fn relative_h_and_v_become_absolute_lines_from_the_current_point() {
        let lines = [PathCommand::M(1.0, 2.0), PathCommand::L(4.0, 2.0), PathCommand::L(4.0, 0.0)];
        assert_eq!(parsed("M1 2h3v-2"), lines);
    }

    #[test]
    fn a_relative_command_after_z_starts_from_the_subpath_start() {
        let commands = parsed("M1 1L5 1L5 4Zh2v3");
        assert_eq!(commands[4..], [PathCommand::L(3.0, 1.0), PathCommand::L(3.0, 4.0)]);
    }

    #[test]
    fn a_crisp_key_draws_its_tile_at_full_scale() {
        let tile = Tile { width: 4.0, height: 4.0, spacing: 4.0, coverage: 0.375, key_window: [0.0, 0.0], crisp: true, marks: Vec::new() };
        let key = key_node("k", "t", &tile, "#123456");
        assert_eq!(key.children()[0].affine().apply((1.0, 1.0)), (1.0, 1.0));
    }

    #[test]
    fn every_shipped_key_window_sits_inside_its_tile() {
        let lib = shipped();
        let steps = lib.ramps.values().flat_map(|by_count| by_count.values().flatten()).map(|step| &step.tile);
        for tile in lib.motifs.values().chain(steps) {
            let [x, y] = tile.key_window;
            assert!((0.0..tile.width).contains(&x) && (0.0..tile.height).contains(&y));
        }
    }

    #[test]
    fn the_shipped_library_parses_with_every_contract_motif_and_ramp() {
        let lib = shipped();
        for name in [
            "hatch-45", "hatch-135", "bluenoise-dots", "dash-field", "bendday-hex", "worms-fine", "crosshatch", "pebbles-fine",
        ] {
            let tile = &lib.motifs[name];
            assert_eq!(tile.width % 4.0, 0.0, "{name}: tile periods are multiples of 4");
            assert_eq!(tile.height % 4.0, 0.0, "{name}: tile periods are multiples of 4");
            assert!(!tile.marks.is_empty());
        }
        for name in ["hatch-crosshatch", "dots", "hatch-dots"] {
            for n in 3..=9 {
                assert_eq!(lib.ramps[name][&n.to_string()].len(), n, "{name} at {n} steps");
            }
        }
        for name in ["dots-brick", "grid", "hatch-0", "hatch-90"] {
            assert!(lib.motifs.contains_key(name), "{name}");
        }
    }
}
