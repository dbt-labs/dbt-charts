"""dbt exposures derived from boards: one `dashboard` exposure per board.

`depends_on` lists every ref()/source() call in the board's SQL verbatim, so
`dbt parse` — not a possibly stale manifest — checks each one resolves.
Boards with no dbt calls are not dbt consumers and are reported as skipped;
a board that does not compile, or a dbt call this engine cannot read, is an
error: leaving that board out would read as "nothing depends on this model".
"""

from __future__ import annotations

import re
from pathlib import PurePosixPath

import yaml
from pydantic import BaseModel, ConfigDict

from dbt_charts.core.compile.compiler import compile_file
from dbt_charts.core.compile.config import load_config
from dbt_charts.core.compile.errors import CompilationError
from dbt_charts.core.compile.models.config import ExposureOwner
from dbt_charts.core.compile.models.query.normalized import is_sql_query
from dbt_charts.core.execute.dbt_jinja import (
    REF_CALL_RE,
    SOURCE_CALL_RE,
    first_dbt_call,
    has_dbt_jinja,
)
from dbt_charts.core.inspect.manifest_utils import INSPECT_TEMPLATE_MANIFEST
from dbt_charts.core.project import Project, assert_relpath, board_slug
from dbt_charts.core.utils import YAML_LOADER

_HEADER = (
    "# Generated by `dct exposures` from the boards under charts/.\n"
    "# Do not edit: change the board and re-run `dct exposures`.\n"
)


class ExposuresError(ValueError):
    pass


class DbtExposure(BaseModel):
    model_config = ConfigDict(frozen=True)

    name: str
    board: str
    label: str
    description: str
    tags: tuple[str, ...]
    depends_on: tuple[str, ...]
    queries: dict[str, tuple[str, ...]]


class SkippedBoard(BaseModel):
    model_config = ConfigDict(frozen=True)

    board: str
    reason: str


class ExposuresResult(BaseModel):
    model_config = ConfigDict(frozen=True)

    path: str
    """Output file, relative to the dbt project root."""
    changed: bool
    """The file was rewritten, or under check would be."""
    exposures: tuple[DbtExposure, ...]
    skipped: tuple[SkippedBoard, ...]


def emit_exposures(project: Project, check: bool) -> ExposuresResult:
    """Write the exposures file; with *check*, only report whether it is stale."""
    config = load_config(project).exposures
    if config is None:
        raise ExposuresError(
            "dbt_charts.yml has no exposures.owner; dbt requires an owner on "
            "every exposure. Add:\n\nexposures:\n  owner:\n    name: <team>\n"
            "    email: <address>"
        )
    dbt_project = project.manifest_project()
    path = _assert_under_model_paths(dbt_project, config.path)

    exposures, skipped = _build(project)
    text = _render(exposures, config.owner)
    current = dbt_project.read_text(path) if dbt_project.exists(path) else None
    changed = current != text
    if changed and not check:
        dbt_project.write_text(path, text)
    return ExposuresResult(
        path=path, changed=changed, exposures=exposures, skipped=skipped
    )


def _build(
    project: Project,
) -> tuple[tuple[DbtExposure, ...], tuple[SkippedBoard, ...]]:
    exposures: dict[str, DbtExposure] = {}
    skipped: list[SkippedBoard] = []
    errors: list[str] = []
    for board_path in project.iter_boards():
        if (
            board_path.is_meta
            or (board_path.parent / INSPECT_TEMPLATE_MANIFEST).exists()
        ):
            continue
        relpath = board_path.relpath
        try:
            result = compile_file(board_path.read_board())
        except (OSError, UnicodeDecodeError, CompilationError) as exc:
            errors.append(f"{relpath}: does not compile: {exc}")
            continue
        board = result.board
        if board is None:
            reasons = "; ".join(e.message for e in result.errors)
            errors.append(f"{relpath}: does not compile: {reasons}")
            continue
        queries: dict[str, tuple[str, ...]] = {}
        for name, query in result.query_registry.items():
            if not is_sql_query(query):
                continue
            sql = query.sql + "\n" + (query.setup_sql or "")
            calls = _dbt_calls(sql)
            if isinstance(calls, str):
                errors.append(f"{relpath}: query {name}: {calls}")
            elif calls:
                queries[name] = calls
        if not queries:
            skipped.append(SkippedBoard(board=relpath, reason="no ref() or source()"))
            continue
        name = _exposure_name(board_slug(relpath))
        if name in exposures:
            errors.append(
                f"{relpath} and {exposures[name].board} both map to exposure "
                f"name {name}; rename one board"
            )
            continue
        exposures[name] = DbtExposure(
            name=name,
            board=relpath,
            label=board.title,
            description=board.notes,
            tags=tuple(board.tags),
            depends_on=tuple(sorted({c for cs in queries.values() for c in cs})),
            queries=dict(sorted(queries.items())),
        )
    if errors:
        raise ExposuresError(
            "cannot derive exposures:\n" + "\n".join(f"  {e}" for e in errors)
        )
    return tuple(exposures[n] for n in sorted(exposures)), tuple(skipped)


def _dbt_calls(sql: str) -> tuple[str, ...] | str:
    """Sorted dbt dependency expressions in *sql*, or why one cannot be read."""
    calls = {f"ref('{m.group(1)}')" for m in REF_CALL_RE.finditer(sql)}
    calls |= {
        f"source('{m.group(1)}', '{m.group(2)}')" for m in SOURCE_CALL_RE.finditer(sql)
    }
    rest = SOURCE_CALL_RE.sub("", REF_CALL_RE.sub("", sql))
    if has_dbt_jinja(rest):
        return f"unsupported dbt call {first_dbt_call(rest)}"
    return tuple(sorted(calls))


def _exposure_name(slug: str) -> str:
    """dbt exposure names are [A-Za-z0-9_]; `/` becomes `__` to keep the path legible."""
    return re.sub(r"[^A-Za-z0-9_]", "_", slug.replace("/", "__"))


def _assert_under_model_paths(dbt_project: Project, path: str) -> str:
    data = yaml.load(dbt_project.read_text("dbt_project.yml"), Loader=YAML_LOADER)
    # dbt's own default when the key is absent.
    model_paths = data.get("model-paths", ["models"])
    try:
        relpath = assert_relpath(path)
        roots = [assert_relpath(p) for p in model_paths]
    except ValueError as exc:
        raise ExposuresError(f"exposures.path {path}: {exc}") from exc
    target = PurePosixPath(relpath)
    if target.suffix not in {".yml", ".yaml"}:
        raise ExposuresError(
            f"exposures.path {path} must be a YAML file ending in .yml or .yaml"
        )
    if not any(target.is_relative_to(r) for r in roots):
        raise ExposuresError(
            f"exposures.path {path} is outside dbt_project.yml's model-paths "
            f"{model_paths}; dbt would never read it"
        )
    return relpath


def _render(exposures: tuple[DbtExposure, ...], owner: ExposureOwner) -> str:
    owner_doc = owner.model_dump(exclude_none=True)
    docs = []
    for e in exposures:
        doc: dict[str, object] = {
            "name": e.name,
            "type": "dashboard",
            "owner": dict(owner_doc),
        }
        if e.label:
            doc["label"] = e.label
        if e.description:
            doc["description"] = e.description
        config: dict[str, object] = {}
        if e.tags:
            config["tags"] = list(e.tags)
        doc["depends_on"] = list(e.depends_on)
        config["meta"] = {
            "dbt_charts": {
                "board": e.board,
                "queries": {q: list(cs) for q, cs in e.queries.items()},
            }
        }
        doc["config"] = config
        docs.append(doc)
    body = yaml.safe_dump({"exposures": docs}, sort_keys=False, allow_unicode=True)
    return _HEADER + body
