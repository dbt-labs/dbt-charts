"""Unified diagnostic registry: codes, doc pointers, and did-you-mean hints.

Importing this package side-effect-registers every code module so a single
``from dbt_charts.core.diagnostics import REGISTRY`` is enough to look up any
code by string at runtime. The registry is complete the moment this package
is imported — no test, generator, or model may depend on import order.
"""

